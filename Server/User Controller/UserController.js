    const googleLogin = async (req,res)=>{
        try {
            console.log("GOOGLE LOGIN:", req.body);

            const { email, username } = req.body;

            if(!email) {
                return res.status(400).json({message:`Email from Google is required.`})
            }

            let user = await UserModel.findOne({email})
            console.log(user);

            // Auto-register khusus Google: email sudah diverifikasi Google,
            let isNewUser = false
            let plainPasswordForEmail = null
            if(!user) {
                plainPasswordForEmail = generateGooglePassword(12)

                const hashedPassword = await bcrypt.hash(plainPasswordForEmail,10)

                user = await UserModel({
                    email,
                    username: username || email.split("@")[0],
                    password: hashedPassword,
                    isVerified: true
                })

                await user.save()
                isNewUser = true
                console.log("GOOGLE LOGIN: new user created", user.email);

                // Kirim plain password (SEBELUM hash) agar bisa dipakai login manual.
                try {
                    const subject = `Account created VIA Google`
                    const emailbody = `<p>Account created successfully via Google login.</p><p>Your password for manual login is: <b>${plainPasswordForEmail}</b></p><p>Please keep it safe and change it soon.</p>`
                    await sendEmail(email,subject,emailbody)
                    console.log("GOOGLE LOGIN: password email sent to", email);
                } catch (mailError) {
                    console.log("GOOGLE LOGIN: failed to send password email, login continues:", mailError?.message || mailError);
                }
            }

            // Khusus path Google: email terbukti milik user, auto-verify jika belum.
            // Flow login manual tetap menolak belum-verified (tidak diubah).
            if(!user.isVerified){
                user.isVerified = true
                await user.save()
            }

            // create JWT (tanpa cek password, karena identitas sudah diverifikasi Google)
            const jwtPayload = {
                id : user.id
            }

            const token = jwt.sign(jwtPayload,process.env.SECRET,{expiresIn:'10m'})
            console.log(token);

            res.json({message: isNewUser ? `Google account created & logged in successful` : `Google login successful`,token})
        } catch (error) {
            console.log("GOOGLE LOGIN ERROR:", error);
            res.status(500).json({message:`Something went wrong`})
        }
    }

