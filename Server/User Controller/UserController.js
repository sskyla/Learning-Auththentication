// Generate password yang dijamin lolos passwordRegex frontend:
// /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[@$!%*?&])[A-Za-z\d@$!%*?&]{8,}$/
// otp-generator memakai special '#!&@' (ada '#' yang ditolak frontend) dan
// tidak menjamin tiap kategori muncul, jadi tidak dipakai untuk password Google.
const GOOGLE_PASSWORD_REGEX = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[@$!%*?&])[A-Za-z\d@$!%*?&]{8,}$/
const generateGooglePassword = (length = 12) => {
    const lower = 'abcdefghjkmnpqrstuvwxyz'
    const upper = 'ABCDEFGHJKMNPQRSTUVWXYZ'
    const digits = '23456789'
    const specials = '@$!%*?&'
    const all = lower + upper + digits + specials
    for (let attempt = 0; attempt < 5; attempt++) {
        const chars = [
            lower[crypto.randomInt(0, lower.length)],
            upper[crypto.randomInt(0, upper.length)],
            digits[crypto.randomInt(0, digits.length)],
            specials[crypto.randomInt(0, specials.length)],
        ]
        while (chars.length < length) {
            chars.push(all[crypto.randomInt(0, all.length)])
        }
        // shuffle Fisher-Yates agar posisi kategori wajib acak
        for (let i = chars.length - 1; i > 0; i--) {
            const j = crypto.randomInt(0, i + 1)
            ;[chars[i], chars[j]] = [chars[j], chars[i]]
        }
        const password = chars.join('')
        if (GOOGLE_PASSWORD_REGEX.test(password)) return password
    }
    throw new Error('Failed to generate compliant password')
}


const register = async (req,res)=>{
    try {

        console.log(req.body);

        const isUserExisting = await UserModel.findOne({email:req.body.email})

        if(isUserExisting) {
            console.log("User already exists");
            
            return res.status(400).json({message:`User with ${req.body.email} already existing.`})
        }

        const verificationToken = otp_generator.generate(6,{upperCaseAlphabets: false, specialChars: false})

        const expires = new Date();
        expires.setMinutes(expires.getMinutes() + 5);

        const hashedPassword = await bcrypt.hash(req.body.password,10)

        const newUser = await UserModel({
            email: req.body.email,
            username: req.body.username,
            password: hashedPassword,
            verificationToken: {
                token: verificationToken,
                expires: expires

            }
        })

        console.log(newUser);
        await newUser.save()

        const emailbody = `<p>Please click on the link verify your account <b>http://localhost:5000/user/verify/${verificationToken}</b>VERIFY ACCOUNT</p>`
        const subject = `Verification Email`

        await sendEmail(req.body.email,subject,emailbody)
        



        res.json({message:"Verification link sent to your EMAIL."})
    } catch (error) {
        res.json({message: "Something went wrong"})
    }
}

